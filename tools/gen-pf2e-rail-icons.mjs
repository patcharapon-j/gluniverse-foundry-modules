/**
 * tools/gen-pf2e-rail-icons.mjs — the skill finder's action icons.
 *
 * PF2e ships no icon per skill action, so the finder borrows silhouettes from
 * game-icons.net (https://github.com/game-icons/icons), licensed CC BY 3.0:
 * free to use, with the artists credited. This script fetches the chosen
 * icons, keeps only each one's figure path (the source draws a black 512²
 * square behind a white figure; the square is dropped and the figure is
 * filled with `currentColor`, so it takes the rail's ink and paper), and
 * writes:
 *
 *   scripts/features/pf2e-rail/action-icons.mjs   the paths, keyed by PF2e action slug
 *   assets/pf2e-rail/CREDITS.md                   who drew what, under which licence
 *
 * Run it again after changing `PICKS`; it needs the network once and never at
 * runtime. The output is committed, so Foundry and the preview read no file.
 *
 *   node tools/gen-pf2e-rail-icons.mjs
 */
