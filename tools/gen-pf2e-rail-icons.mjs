/* The figure: every path but the 512² background square. */
const BACKGROUND = /^M0 0h512v512H0z$/;
function figure(svg) {
  const ds = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((m) => m[1].trim()).filter((d) => !BACKGROUND.test(d));
  if (!ds.length) throw new Error("no figure path");
  return ds.join(" ");
}

const out = {};
for (const [slug, src] of Object.entries(PICKS)) {
  const res = await fetch(`${RAW}${src}.svg`);
  if (!res.ok) throw new Error(`${src}: HTTP ${res.status}`);
  out[slug] = figure(await res.text());
}

const ICONS = resolve(ROOT, "scripts/features/pf2e-rail/action-icons.mjs");
await writeFile(ICONS, `/**
 * The skill finder's action icons: game-icons.net silhouettes, CC BY 3.0,
 * credited in assets/pf2e-rail/CREDITS.md. GENERATED by
 * tools/gen-pf2e-rail-icons.mjs — edit PICKS there and run it again.
 *
 * Each value is one SVG path on a 512 grid, filled with currentColor. Pure.
 */
export const ACTION_ICON = Object.freeze(${JSON.stringify(out, null, 2)});

/** The icon for an action slug, or "" when it has none. */
export const actionIcon = (slug, cls = "gph-aic") => (ACTION_ICON[slug]
  ? \`<svg class="\${cls}" viewBox="0 0 512 512" aria-hidden="true" focusable="false"><path d="\${ACTION_ICON[slug]}"/></svg>\`
  : "");
`);

